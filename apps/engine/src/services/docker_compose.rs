    async fn wait_for_posthog_health(&self, service_id: Uuid, service_dir: &Path) -> bool {
        // PostHog first-run includes DB migrations + ClickHouse migrations which can
        // take 5-10 minutes, so we allow up to 180 attempts * 5s = 15 minutes.
        let required_healthy = ["posthog-db", "posthog-redis", "posthog-clickhouse", "posthog-kafka"];

        for attempt in 1..=180 {
            tokio::time::sleep(std::time::Duration::from_secs(5)).await;

            let output = tokio::process::Command::new("docker")
                .args(["compose", "ps", "--format", "json"])
                .current_dir(service_dir)
                .output()
                .await;

            let output = match output {
                Ok(o) if o.status.success() => String::from_utf8_lossy(&o.stdout).to_string(),
                _ => {
                    if attempt % 10 == 0 {
                        self.log(
                            service_id,
                            "info",
                            &format!("Waiting for services... (attempt {attempt}/180)"),
                            "system",
                        )
                        .await
                        .ok();
                    }
                    continue;
                }
            };

            let mut all_healthy = true;
            let mut found = std::collections::HashSet::new();
            let mut web_running = false;

            for line in output.lines() {
                if let Ok(v) = serde_json::from_str::<serde_json::Value>(line) {
                    let service = v["Service"].as_str().unwrap_or("");
                    let health = v["Health"].as_str().unwrap_or("");
                    let state = v["State"].as_str().unwrap_or("");

                    if required_healthy.contains(&service) {
                        found.insert(service.to_string());
                        if health != "healthy" {
                            all_healthy = false;
                        }
                    }
                    if service == "posthog-web" && state == "running" {
                        web_running = true;
                    }
                }
            }

            if all_healthy && found.len() == required_healthy.len() && web_running {
                self.log(
                    service_id,
                    "info",
                    &format!("All services healthy (attempt {attempt}/180)"),
                    "system",
                )
                .await
                .ok();
                return true;
            }

            if attempt % 10 == 0 {
                let pending: Vec<_> = required_healthy
                    .iter()
                    .filter(|s| !found.contains(**s))
                    .copied()
                    .collect();
                self.log(
                    service_id,
                    "info",
                    &format!(
                        "Waiting for services... (attempt {attempt}/180, pending: {})",
                        if pending.is_empty() { "checking health".to_string() } else { pending.join(", ") }
                    ),
                    "system",
                )
                .await
                .ok();
            }
        }

        false
    }

