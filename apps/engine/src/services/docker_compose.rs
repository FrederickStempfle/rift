    /// Connect the engine container to the Supabase service's Docker network.
    /// This allows the proxy to forward requests to containers (kong, studio)
    /// by their internal hostnames. The Supabase DB is named 'supabase-db' to
    /// avoid DNS conflicts with the Rift 'db' on the engine's default network.
    /// Silently ignores errors (e.g., already connected, not in Docker).
    pub async fn connect_engine_to_service_network(&self, service_id: Uuid) {
        // Detect our container ID from /etc/hostname (Docker sets this).
        let hostname = match tokio::fs::read_to_string("/etc/hostname").await {
            Ok(h) => h.trim().to_string(),
            Err(_) => return, // Not in a container — localhost works fine in dev
        };
        if hostname.is_empty() {
            return;
        }

        let network = format!("{}_default", service_id);
        let result = tokio::process::Command::new("docker")
            .args(["network", "connect", &network, &hostname])
            .output()
            .await;

        match result {
            Ok(output) if output.status.success() => {
                self.log(
                    service_id,
                    "info",
                    &format!("Connected engine to service network {network}"),
                    "system",
                )
                .await
                .ok();
            }
            Ok(output) => {
                let stderr = String::from_utf8_lossy(&output.stderr);
                // "already exists" means we're already connected — not an error
                if !stderr.contains("already exists") {
                    self.log(
                        service_id,
                        "warn",
                        &format!("Could not connect to service network: {}", stderr.trim()),
                        "system",
                    )
                    .await
                    .ok();
                }
            }
            Err(_) => {} // Docker command not available
        }
    }

    async fn run_compose_command(
        &self,
        service_dir: &Path,
        args: &[&str],
        service_id: Uuid,
    ) -> Result<(), AppError> {
        let mut cmd = tokio::process::Command::new("docker");
        cmd.arg("compose")
            .args(args)
            .current_dir(service_dir)
            .stdout(Stdio::piped())
            .stderr(Stdio::piped());

        let display = format!("docker compose {}", args.join(" "));
        self.log(service_id, "info", &format!("$ {display}"), "docker")
            .await?;

        let mut child = cmd.spawn().map_err(|e| {
            AppError::Internal(format!("failed to spawn '{display}': {e}"))
        })?;

        let stdout = child.stdout.take();
        let stderr = child.stderr.take();

        let pool_clone = self.pool.clone();
        let broadcaster_clone = self.service_log_broadcaster.clone();
        let sid = service_id;

        let stdout_task = tokio::spawn(async move {
            if let Some(stream) = stdout {
                let mut lines = BufReader::new(stream).lines();
                while let Ok(Some(line)) = lines.next_line().await {
                    let _ = insert_and_broadcast_service_log(
                        &pool_clone,
                        &broadcaster_clone,
                        sid,
                        "info",
                        &line,
                        "docker",
                    )
                    .await;
                }
            }
        });

        let pool_clone2 = self.pool.clone();
        let broadcaster_clone2 = self.service_log_broadcaster.clone();

        let stderr_task = tokio::spawn(async move {
            if let Some(stream) = stderr {
                let mut lines = BufReader::new(stream).lines();
                while let Ok(Some(line)) = lines.next_line().await {
                    let _ = insert_and_broadcast_service_log(
                        &pool_clone2,
                        &broadcaster_clone2,
                        sid,
                        "error",
                        &line,
                        "docker",
                    )
                    .await;
                }
            }
        });

        let status = child.wait().await.map_err(|e| {
            AppError::Internal(format!("failed waiting for '{display}': {e}"))
        })?;

        let _ = stdout_task.await;
        let _ = stderr_task.await;

        if status.success() {
            Ok(())
        } else {
            Err(AppError::Internal(format!(
                "command failed with status {:?}: {display}",
                status.code()
            )))
        }
    }

    async fn wait_for_health(&self, service_id: Uuid, service_dir: &Path, required_healthy: &[&str]) -> bool {
        // Check health via `docker compose ps --format json` since the engine
        // container can't reach published ports on the host network.

        for attempt in 1..=90 {
            tokio::time::sleep(std::time::Duration::from_secs(5)).await;

            let output = tokio::process::Command::new("docker")
                .args(["compose", "ps", "--format", "json"])
                .current_dir(service_dir)
                .output()
                .await;

            let output = match output {
                Ok(o) if o.status.success() => String::from_utf8_lossy(&o.stdout).to_string(),
                _ => {
                    if attempt % 10 == 0 {
                        self.log(
                            service_id,
                            "info",
                            &format!("Waiting for services... (attempt {attempt}/90)"),
                            "system",
                        )
                        .await
                        .ok();
                    }
                    continue;
                }
            };

            // Parse each line as JSON, check Health field for required services
            let mut all_healthy = true;
            let mut found = std::collections::HashSet::new();
            for line in output.lines() {
                if let Ok(v) = serde_json::from_str::<serde_json::Value>(line) {
                    let service = v["Service"].as_str().unwrap_or("");
                    let health = v["Health"].as_str().unwrap_or("");
                    if required_healthy.contains(&service) {
                        found.insert(service.to_string());
                        if health != "healthy" {
                            all_healthy = false;
                        }
                    }
                }
            }

            if all_healthy && found.len() == required_healthy.len() {
                self.log(
                    service_id,
                    "info",
                    &format!("All services healthy (attempt {attempt}/90)"),
                    "system",
                )
                .await
                .ok();
                return true;
            }

            if attempt % 10 == 0 {
                let unhealthy: Vec<_> = required_healthy
                    .iter()
                    .filter(|s| !found.contains(**s))
                    .copied()
                    .collect();
                self.log(
                    service_id,
                    "info",
                    &format!(
                        "Waiting for services... (attempt {attempt}/90, pending: {})",
                        if unhealthy.is_empty() { "checking health".to_string() } else { unhealthy.join(", ") }
                    ),
                    "system",
                )
                .await
                .ok();
            }
        }

        false
    }

