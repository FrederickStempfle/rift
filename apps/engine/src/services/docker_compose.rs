    pub async fn deploy_posthog(&self, service_id: Uuid) -> Result<(), AppError> {
        let service_dir = self.data_dir.join(service_id.to_string());
        tokio::fs::create_dir_all(&service_dir)
            .await
            .map_err(|e| AppError::Internal(format!("failed to create service dir: {e}")))?;

        db_services::update_status(&self.pool, service_id, "deploying", None).await?;

        self.log(service_id, "info", "Generating PostHog configuration...", "system")
            .await?;

        let secret_key = generate_hex_string(56);
        let encryption_salt = generate_hex_string(32);
        let postgres_password = generate_random_string(32);

        // Clone PostHog repo for ClickHouse config files
        self.log(service_id, "info", "Cloning PostHog repository for config files...", "system")
            .await?;

        let posthog_repo_dir = service_dir.join("posthog");
        if posthog_repo_dir.exists() {
            tokio::fs::remove_dir_all(&posthog_repo_dir).await.ok();
        }

        let clone_output = tokio::process::Command::new("git")
            .args([
                "clone",
                "--depth=1",
                "--filter=blob:none",
                "--sparse",
                "https://github.com/PostHog/posthog.git",
                "posthog",
            ])
            .current_dir(&service_dir)
            .output()
            .await
            .map_err(|e| AppError::Internal(format!("failed to clone PostHog repo: {e}")))?;

        if !clone_output.status.success() {
            let err = String::from_utf8_lossy(&clone_output.stderr);
            let err_msg = format!("Failed to clone PostHog repo: {err}");
            self.log(service_id, "error", &err_msg, "system").await?;
            db_services::update_status(&self.pool, service_id, "failed", Some(&err_msg)).await?;
            return Err(AppError::Internal(err_msg));
        }

        // Sparse checkout only the dirs we need
        let sparse_output = tokio::process::Command::new("git")
            .args([
                "sparse-checkout",
                "set",
                "docker/clickhouse",
                "posthog/idl",
                "posthog/user_scripts",
            ])
            .current_dir(&posthog_repo_dir)
            .output()
            .await
            .map_err(|e| AppError::Internal(format!("failed to sparse-checkout: {e}")))?;

        if !sparse_output.status.success() {
            let err = String::from_utf8_lossy(&sparse_output.stderr);
            self.log(service_id, "warn", &format!("sparse-checkout warning: {err}"), "system")
                .await?;
        }

        self.log(service_id, "info", "Writing environment configuration...", "system")
            .await?;

        let env_content = format!(
            r#"# PostHog Configuration (auto-generated by Rift)
POSTHOG_SECRET={secret_key}
ENCRYPTION_SALT_KEYS={encryption_salt}
POSTGRES_PASSWORD={postgres_password}
POSTHOG_WEB_PORT={web_port}
SITE_URL={scheme}://{public_host}:{web_port}
"#,
            secret_key = secret_key,
            encryption_salt = encryption_salt,
            postgres_password = postgres_password,
            scheme = self.proxy_scheme,
            public_host = self.public_host,
            web_port = self.posthog_web_port,
        );

        tokio::fs::write(service_dir.join(".env"), &env_content)
            .await
            .map_err(|e| AppError::Internal(format!("failed to write .env: {e}")))?;

        self.log(service_id, "info", "Writing Docker Compose manifest...", "system")
            .await?;

        let compose_content = generate_posthog_compose();
        tokio::fs::write(service_dir.join("docker-compose.yml"), &compose_content)
            .await
            .map_err(|e| AppError::Internal(format!("failed to write docker-compose.yml: {e}")))?;

        // Create compose/start and compose/wait scripts (mimics PostHog deploy-hobby)
        self.write_posthog_scripts(&service_dir).await?;

        self.log(service_id, "info", "Pulling PostHog Docker images...", "docker")
            .await?;

        if let Err(e) = self
            .run_compose_command(&service_dir, &["pull"], service_id)
            .await
        {
            let err_msg = format!("Failed to pull images: {e}");
            self.log(service_id, "error", &err_msg, "docker").await?;
            db_services::update_status(&self.pool, service_id, "failed", Some(&err_msg)).await?;
            return Err(e);
        }

        self.log(service_id, "info", "Starting PostHog services...", "docker")
            .await?;

        if let Err(e) = self
            .run_compose_command(&service_dir, &["up", "-d"], service_id)
            .await
        {
            let err_msg = format!("Failed to start services: {e}");
            self.log(service_id, "error", &err_msg, "docker").await?;
            db_services::update_status(&self.pool, service_id, "failed", Some(&err_msg)).await?;
            return Err(e);
        }

        self.connect_engine_to_service_network(service_id).await;

        self.log(service_id, "info", "Waiting for PostHog to be ready (this may take several minutes on first run — migrations are running)...", "system")
            .await?;

        let healthy = self
            .wait_for_posthog_health(service_id, &service_dir)
            .await;

        if healthy {
            let connection_info = serde_json::json!({
                "app_url": format!("{}://{}:{}", self.proxy_scheme, self.public_host, self.posthog_web_port),
                "internal_app_url": format!("http://{}-posthog-web-1:8000", service_id),
            });

            db_services::update_connection_info(&self.pool, service_id, &connection_info).await?;
            db_services::update_status_started(&self.pool, service_id, "running").await?;

            self.log(service_id, "info", "PostHog is ready!", "system")
                .await?;
        } else {
            let err_msg = "Health check timed out — PostHog may still be starting. Check logs for details.";
            self.log(service_id, "warn", err_msg, "system").await?;
            db_services::update_status(&self.pool, service_id, "failed", Some(err_msg)).await?;
        }

        Ok(())
    }

