async fn insert_and_broadcast_service_log(
    pool: &sqlx::PgPool,
    broadcaster: &ServiceLogBroadcaster,
    service_id: Uuid,
    level: &str,
    message: &str,
    source: &str,
) -> Result<(), AppError> {
    let log = db_services::insert_log_returning(pool, service_id, level, message, source).await?;
    broadcaster
        .send(
            service_id,
            ServiceLogMessage {
                id: log.id,
                service_id: log.service_id,
                timestamp: log.timestamp,
                level: log.level,
                message: log.message,
                source: log.source,
            },
        )
        .await;
    Ok(())
}

fn generate_random_string(len: usize) -> String {
    let mut rng = rand::thread_rng();
    let chars: Vec<char> = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
        .chars()
        .collect();
    (0..len).map(|_| chars[rng.gen_range(0..chars.len())]).collect()
}

fn generate_hex_string(len: usize) -> String {
    let mut rng = rand::thread_rng();
    let hex_chars: Vec<char> = "0123456789abcdef".chars().collect();
    (0..len).map(|_| hex_chars[rng.gen_range(0..hex_chars.len())]).collect()
}

