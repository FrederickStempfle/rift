    pub async fn remove_supabase(&self, service_id: Uuid) -> Result<(), AppError> {
        let service_dir = self.data_dir.join(service_id.to_string());
        db_services::update_status(&self.pool, service_id, "removing", None).await?;

        self.log(service_id, "info", "Removing Supabase services and volumes...", "docker")
            .await?;

        // Ignore errors during removal — service dir may not exist
        let _ = self
            .run_compose_command(&service_dir, &["down", "-v", "--remove-orphans"], service_id)
            .await;

        // Clean up the service directory
        let _ = tokio::fs::remove_dir_all(&service_dir).await;

        self.log(service_id, "info", "Supabase removed.", "system")
            .await?;

        Ok(())
    }

